// Declares and defines a variable for a data placeholder.
#define INTERNAL_DEFINE_CONSTANT_PLACEHOLDER(ordinal, constant_type) \
    using _CONSTANT_PLACEHOLDER_TYPE_##ordinal = constant_type; \
    union _UNION_CONSTANT_PLACEHOLDER_TYPE_##ordinal { \
        uint64_t _dummy; \
        _CONSTANT_PLACEHOLDER_TYPE_##ordinal _actual_value; \
    }; \
    const uintptr_t _DONOTUSE_INTERNAL_CONSTANT_PLACEHOLDER_##ordinal = \
        reinterpret_cast<uintptr_t>(__dyn_specialization_data_placeholder_##ordinal); \
    const _CONSTANT_PLACEHOLDER_TYPE_##ordinal CONSTANT_PLACEHOLDER_##ordinal = \
        reinterpret_cast<const _UNION_CONSTANT_PLACEHOLDER_TYPE_##ordinal *>( \
            &_DONOTUSE_INTERNAL_CONSTANT_PLACEHOLDER_##ordinal \
        )->_actual_value

// An array index.
#define INTERNAL_DEFINE_INDEX_CONSTANT_PLACEHOLDER(ordinal) \
    const uint64_t CONSTANT_PLACEHOLDER_##ordinal = reinterpret_cast<uint64_t>(\
        __dyn_specialization_data_placeholder_##ordinal \
    )

