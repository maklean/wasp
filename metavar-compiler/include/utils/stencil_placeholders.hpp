#define INTERNAL_INTERNAL_DEFINE_BOILERPLATE_FNPTR_PLACEHOLDER(symbol, ordinal, fn_type) \
    using _BOILERPLATE_FNPTR_PLACEHOLDER_TYPE_##ordinal = fn_type; \
